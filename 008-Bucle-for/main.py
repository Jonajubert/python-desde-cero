# EJEMPLO 1
# Recorremos números del 1 al 5.

for numero in range(1, 6):
    print(numero)


# EJEMPLO 2
# Recorremos los elementos de una lista.

lenguajes = ["Python", "C#", "JavaScript"]

for lenguaje in lenguajes:
    print(lenguaje)


# EJEMPLO 3
# Utilizamos un incremento diferente.

for numero in range(0, 11, 2):
    print(numero)
