# Variables utilizadas en los ejemplos
numero1 = 20
numero2 = 10

print("=== OPERADORES EN PYTHON ===\n")

# Operadores aritméticos
print("Suma:", numero1 + numero2)
print("Resta:", numero1 - numero2)
print("Multiplicación:", numero1 * numero2)
print("División:", numero1 / numero2)

print()

# Operadores de comparación
print("¿20 es mayor que 10?:", numero1 > numero2)
print("¿20 es igual a 10?:", numero1 == numero2)

print()

# Operadores lógicos
print("True and False =", True and False)
print("True or False =", True or False)
print("not True =", not True)
